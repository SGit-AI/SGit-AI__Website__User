#!/usr/bin/env python3
"""Generates llms-full.txt, the whole site in one fetch.

Run from anywhere: python3 admin/build/gen_llms_full.py

Agent fetch tools frequently refuse URLs a search has not already returned, which
makes link-following unreliable and a single-file surface the practical one. This
concatenates llms.txt, the front page's markdown twin, and the text of every page
under the content directories, in reading order, with the HTML stripped. It is a
convenience over the pages, never the source of truth.
"""
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VERSION = (ROOT / "admin/build/version.txt").read_text().strip()
ORDER = ["account/index.html", "workflows/index.html", "billing/index.html",
         "lab/index.html", "shipped/index.html", "sources/index.html",
         "network/index.html", "admin/comms.html", "admin/versions.html",
         "admin/index.html"]

HEADER = f"""# users.sgit.ai, everything, in one file

Site version: {VERSION}. Generated by admin/build/gen_llms_full.py, do not edit by hand.

This is /llms.txt, then the front page, then the text of every page, in reading
order, with the markup stripped. If you can make more than one request, prefer the
pages at https://users.sgit.ai/ (each is hand-written HTML a human can read); this
file is a concatenation of them.

All content is released under the Creative Commons Attribution 4.0 International
licence (CC BY 4.0). Third-party material quoted inside stays under its own terms.

"""
SEP = "\n\n" + "=" * 78 + "\n== {name}\n" + "=" * 78 + "\n\n"


def text_of(page):
    t = page.read_text()
    m = re.search(r'<main class="doc">(.*?)</main>', t, re.S)
    body = m.group(1) if m else re.sub(r'<nav class="site">.*?</nav>|<footer class="site">.*?</footer>', '', t, flags=re.S)
    body = re.sub(r'<script.*?</script>|<style.*?</style>', '', body, flags=re.S)
    body = re.sub(r'<span class="who">(.*?)</span>', r' [\1]', body, flags=re.S)
    body = body.replace('</b>', '</b> ')
    body = re.sub(r'<h1[^>]*>(.*?)</h1>', r'\n# \1\n', body, flags=re.S)
    body = re.sub(r'<h2[^>]*>(.*?)</h2>', r'\n## \1\n', body, flags=re.S)
    body = re.sub(r'<h3[^>]*>(.*?)</h3>', r'\n### \1\n', body, flags=re.S)
    body = re.sub(r'<li[^>]*>', '- ', body)
    body = re.sub(r'</(p|li|tr|div|h[1-6]|pre|blockquote)>', '\n', body)
    body = re.sub(r'</t[dh]>', ' | ', body)
    body = re.sub(r'<br\s*/?>', '\n', body)
    body = re.sub(r'<[^>]+>', '', body)
    body = html.unescape(body)
    body = re.sub(r'[ \t]+', ' ', body)
    body = re.sub(r'\n\s*\n\s*\n+', '\n\n', body)
    return body.strip() + "\n"


def main():
    parts = [HEADER, SEP.format(name="llms.txt"), (ROOT / "llms.txt").read_text(),
             SEP.format(name="index.md, the front page"), (ROOT / "index.md").read_text()]
    for rel in ORDER:
        p = ROOT / rel
        if not p.exists():
            print(f"  ! {rel} is missing")
            continue
        parts.append(SEP.format(name=rel))
        parts.append(text_of(p))
    out = ROOT / "llms-full.txt"
    out.write_text("".join(parts))
    print(f"gen_llms_full: {out.name}, {out.stat().st_size:,} bytes, {len(ORDER) + 2} sections")


if __name__ == "__main__":
    main()
